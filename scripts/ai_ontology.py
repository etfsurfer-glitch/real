def render_prompt() -> str:
    lines = ["\n[콕집 데이터 온톨로지 — 용어·라우팅은 반드시 이 정의대로]"]
    lines.append("· 개체와 관계: " + " / ".join(RELATIONS))
    for name, desc in ENTITIES.items():
        lines.append(f"· {name}: {desc}")
    lines.append("· 지표 정의(정의 | 주의):")
    for m, (d, c) in METRICS.items():
        lines.append(f"  - {m}: {d} | {c}")
    lines.append("· 사용자 표현 정규화: " + " / ".join(
        f"'{'·'.join(alts)}'→{std}" for std, alts in SYNONYMS.items()))
    lines.append("· 발화 의도(같은 조건이라도 목적이 다르면 도구가 다르다):")
    for k, (ex, rule) in INTENTS.items():
        lines.append(f"  - {k}: {ex} → {rule}")
    lines.append("· 도구 온톨로지(의도 | 대상 | 제약):")
    for t, (intent, target, constraint) in TOOLS.items():
        lines.append(f"  - {t}: {intent} | {target}" + (f" | {constraint}" if constraint else ""))
    lines.append("· 신도시 별칭→행정지역(도구 region 인자엔 반드시 행정지역을 넣는다. 별칭으로 단지명을 지어내지 말 것): "
                 + " / ".join(f"{k}→{v}" for k, v in REGION_ALIASES.items()))
    lines.append("· 표기 규칙(답변 문장에 그대로 적용): "
                 + " / ".join(f"{k}: {v}" for k, v in UNITS.items()))
    lines.append("· 식별자 체계: " + " / ".join(f"{k}={v}" for k, v in IDENTIFIERS.items()))
    lines.append("· 시점 의미: " + " / ".join(f"{k}: {v}" for k, v in TEMPORAL.items()))
    lines.append("· 콕집이 제공하는 기능(데이터가 없어도 이 기능은 안내할 수 있다): "
                 + " / ".join(f"{k}: {v}" for k, v in SERVICES.items()))
    lines.append("· 데이터가 없는 것(있는 척 금지): " + " / ".join(NOT_COVERED))
    return "\n".join(lines) + "\n"


