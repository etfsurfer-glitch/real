def remap_cortar(cortar):
    """옛 인천 동 cortar면 신코드로, 아니면 그대로."""
    if not cortar:
        return cortar
    return ICN_DONG_REMAP.get(str(cortar), str(cortar))


def is_defunct_region(cortar):
    """소멸된 옛 인천 구·동 region 인지(부활 삽입 차단용)."""
    return bool(cortar) and str(cortar)[:5] in ICN_OLD_GU_PREFIX
